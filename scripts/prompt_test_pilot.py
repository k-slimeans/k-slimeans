"""Write the pilot data of the prompt test (#46): a CSV of surface counts and the side-by-side examples.

Reads the six pilot directories `<pilot-root>/pilot_<old|v2>_<size>/<newest stamp>` that `scripts/fixed_workload.py`
wrote (no model runs), and for the examples rebuilds seed 0's first-step clusters from the logged 4B run named in
the pilot's `config.yaml` (logged partition and cached embeddings; nothing is encoded). `scripts/compare_workloads.py`
prints the same counts as a table; the rows here come from the same `surface.json` files.

Examples are picked by `kslimeans.prompt_test.select_examples`: a seeded draw of clusters the old prompt handled
badly (mentions the cluster, or an exact duplicate, at any size) and of other clusters, three sampled members each.

Usage (from the checkout that holds `results/` and `cache/`):

    python scripts/prompt_test_pilot.py --out-csv docs/results/prompt_test_pilot.csv \\
        --out-examples docs/results/prompt_test_pilot_examples.md
"""

from __future__ import annotations

import argparse
import csv
import random
from pathlib import Path

from kslimeans.prompt_test import (
    CSV_FIELDS,
    PROMPTS,
    SIZES,
    format_example,
    old_prompt_flags,
    latest_stamp,
    pilot_row,
    read_outputs,
    select_examples,
)
from kslimeans.runlog import load_run, load_run_dataset
from kslimeans.workload import build_workload, load_workload_dir, pick_record


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--pilot-root", default="results/fixed_workload", help="holds pilot_<old|v2>_<size>/<stamp>")
    parser.add_argument("--base-dir", default=".", help="what the logged run_dir in the pilot config is relative to")
    parser.add_argument("--cache-dir", default="cache", help="embedding cache")
    parser.add_argument("--out-csv", required=True)
    parser.add_argument("--out-examples", help="write the examples here (default: skip them)")
    parser.add_argument("--n-examples", type=int, default=8)
    parser.add_argument("--n-flagged", type=int, default=3, help="examples drawn from old-prompt duplicates and mentions")
    parser.add_argument("--n-members", type=int, default=3)
    parser.add_argument("--seed", type=int, default=46, help="seed of the example draws")
    args = parser.parse_args()

    dirs = {(p, s): latest_stamp(args.pilot_root, f"pilot_{p}_{s}") for s in SIZES for p in PROMPTS}
    rows = [pilot_row(s, p, dirs[p, s]) for s in SIZES for p in PROMPTS]
    with open(args.out_csv, "w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=CSV_FIELDS, lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)
    print(f"Wrote {args.out_csv}")

    if not args.out_examples:
        return
    old = {s: read_outputs(dirs["old", s]) for s in SIZES}
    new = {s: read_outputs(dirs["v2", s]) for s in SIZES}
    chosen = select_examples(old, n=args.n_examples, n_flagged=args.n_flagged, seed=args.seed)

    # Every size summarizes the same clusters (one step0_sha1), so the 4B's logged run gives the members for all.
    source = load_workload_dir(dirs["old", "4b"])["config"]["source"]
    runlog = load_run(Path(args.base_dir) / source["run_dir"])
    ds, X = load_run_dataset(runlog, cache_dir=args.cache_dir)
    record = pick_record(runlog, source["method"], source["seed"])
    clusters = build_workload(record, source["step"], ds.texts, X, runlog.config.get("force_context_length", 0))
    by_index = {c.index: c for c in clusters}

    flags = old_prompt_flags(old)
    rng = random.Random(args.seed)
    blocks = [
        "<!-- Generated by scripts/prompt_test_pilot.py; do not edit by hand. -->",
        f"Draw seed {args.seed}; seed 0, step 0, step0_sha1 {source['step0_sha1']}.",
    ]
    for index in chosen:
        texts = by_index[index].texts
        members = rng.sample(texts, min(args.n_members, len(texts)))
        blocks.append(
            format_example(
                index, members, {s: old[s][index] for s in SIZES}, {s: new[s][index] for s in SIZES}, flags.get(index, [])
            )
        )
    Path(args.out_examples).write_text("\n\n".join(blocks) + "\n")
    print(f"Wrote {args.out_examples} (clusters {chosen})")


if __name__ == "__main__":
    main()
