"""Real-data grid reproduction check: `kNLPmeans` across method x top_k x max_llm_iter
settings on Bank77, vs. the original code.

Backs the README's claim: "k-NLPmeans grid (Bank77, LSA / centroid / TextRank x top_k
3, 5 x 1 or 5 summary steps, max_iter 120, seed 0): identical assignments, summaries and
summary embeddings in all 12 settings". Marked slow -- computes distilbert embeddings
and builds a Bank77 `SentenceCorpus` once (module-scoped fixtures), then runs our
`kNLPmeans` for each of the 12 settings in `bank77_grid_settings()` and compares against
`bank77_grid_seed0.npz` (generated by `tests/fixtures/make_fixtures.py --bank77-grid`
from the ORIGINAL, un-modified `summaryCentroids.py`).

Only assignments, summaries, and summary embeddings are compared exactly -- they're
pure functions of deterministic inputs (KMeans `init`, extractive scoring,
`embedder.encode`). Centroids are NOT compared: sklearn's multithreaded Lloyd-step
reduction on real (float32) data can differ by ~1 float32 ulp run to run, even between
two calls of upstream's own code (see `test_minibatch.py`'s module docstring for the
same caveat) -- see `tests/fixtures/make_fixtures.py::_make_bank77_grid_fixture`.
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pytest

from kslimeans.core import kNLPmeans
from kslimeans.data import load_dataset
from kslimeans.embeddings import get_embedder
from kslimeans.sentences import SentenceCorpus

FIXTURES = Path(__file__).resolve().parent / "fixtures"
sys.path.insert(0, str(FIXTURES))
from make_fixtures import bank77_grid_key, bank77_grid_settings  # noqa: E402

pytestmark = pytest.mark.slow


@pytest.fixture(scope="module")
def bank77():
    """Real Bank77 texts + distilbert embeddings + a `SentenceCorpus`, built once and
    shared by every setting below (building either from scratch per setting would be
    12x the embedding/spaCy work for no benefit -- every setting uses the same inputs)."""
    dataset = load_dataset("bank77")
    embedder = get_embedder("distilbert")
    X = embedder.encode(dataset.texts)
    sentences = SentenceCorpus.build(dataset.texts, embedder)
    return dataset, X, sentences


@pytest.fixture(scope="module")
def fixture():
    return np.load(FIXTURES / "bank77_grid_seed0.npz", allow_pickle=True)


@pytest.mark.parametrize("method,top_k,max_llm_iter", bank77_grid_settings())
def test_bank77_grid_setting_matches_upstream(bank77, fixture, method, top_k, max_llm_iter):
    dataset, X, sentences = bank77

    result = kNLPmeans(
        dataset.texts,
        dataset.n_clusters,
        force_context_length=0,
        max_llm_iter=max_llm_iter,
        max_iter=120,
        tol=1e-4,
        random_state=0,
        emb_type="distilbert",
        text_features=X,
        nlp=method,
        top_k=top_k,
        text_sentences=sentences,
    )

    key = bank77_grid_key(method, top_k, max_llm_iter)
    assert np.array_equal(result.assignments, fixture[f"{key}_assignments"])
    assert list(result.summaries) == list(fixture[f"{key}_summaries"])
    assert np.array_equal(result.summary_embeddings, fixture[f"{key}_summary_embeddings"])
