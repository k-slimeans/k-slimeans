"""`mini_batch_summary_kmeans` must reproduce upstream `miniBatchSummarymeans`.

Same approach as `test_core_equivalence.py`: re-create the fakes from
`tests/fixtures/synth.py` as `Embedder`/`Summarizer` subclasses, run
`mini_batch_summary_kmeans`, and compare against `.npz` fixtures
generated by `tests/fixtures/make_fixtures.py` from the ORIGINAL,
un-modified `summaryCentroids.py`.

Real-data (bank77) KMeans centroids are NOT bit-reproducible run to run:
sklearn's multithreaded Lloyd-step reduction sums float32 values in a
non-deterministic order, so `KMeans(..., max_iter=60).fit(X)` on the same
`X` can differ by ~1 float32 ulp between two calls, even both being
upstream's own code. The synthetic fixtures below use a fake, tiny,
lookup-table embedder and stay exactly reproducible (matching the rest of
this test suite's convention); the real-data bank77 comparison instead
uses a tolerance on centroids and an agreement threshold on assignments.
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pytest

from kslimeans.embeddings import Embedder
from kslimeans.minibatch import (
    MiniBatchResult,
    _batch_bounds,
    _merge_centroids,
    assign_to_centroids,
    mini_batch_summary_kmeans,
    miniBatchKNLPmeans,
    sequentialMiniBatchKmeans,
)
from kslimeans.schedules import FixedSchedule
from kslimeans.sentences import SentenceCorpus
from kslimeans.summarizers.base import Cluster, Summarizer

FIXTURES = Path(__file__).resolve().parent / "fixtures"
sys.path.insert(0, str(FIXTURES))
from synth import N_BLOBS, closest_to_mean, make_lookup_embedder, make_synthetic_minibatch_data  # noqa: E402


class LookupEmbedder(Embedder):
    """Looks each text up in a fixed table -- see synth.make_lookup_embedder."""

    name = "fake"

    def __init__(self, embed):
        self._embed = embed

    def encode(self, texts):
        return self._embed(list(texts))


class ClosestToMeanSummarizer(Summarizer):
    """Returns the member text closest to the members' mean -- see synth.closest_to_mean."""

    needs_sentences = False

    def __init__(self, embed):
        self._embed = embed

    def summarize(self, cluster: Cluster) -> str:
        return closest_to_mean(list(cluster.texts), self._embed)


@pytest.fixture(scope="module")
def synthetic():
    texts, X = make_synthetic_minibatch_data()
    embed = make_lookup_embedder(texts, X)
    return texts, X, embed


def _load_fixture(name: str):
    return np.load(FIXTURES / name, allow_pickle=True)


def _run(synthetic, *, max_batch_size, max_llm_iter, max_iter, tol, random_state=0):
    texts, X, embed = synthetic
    embedder = LookupEmbedder(embed)
    summarizer = ClosestToMeanSummarizer(embed)
    schedule = FixedSchedule(max_llm_iter, max_iter)
    return mini_batch_summary_kmeans(
        texts,
        N_BLOBS,
        summarizer,
        embedder,
        schedule,
        text_features=X,
        max_batch_size=max_batch_size,
        tol=tol,
        random_state=random_state,
        verbose=False,
    )


# --- batch slicing -----------------------------------------------------------------


def test_batch_bounds_matches_upstream_divmod_formula():
    """320 points / 3 batches -> upstream's (k, m) = divmod(320, 3) = (106, 2)."""
    assert _batch_bounds(320, 3) == [(0, 107), (107, 214), (214, 320)]


@pytest.mark.parametrize(
    "n,num_batches", [(1, 1), (2, 1), (7, 3), (10, 4), (301, 3), (5000, 7), (99, 11)]
)
def test_batch_bounds_covers_range_contiguously_with_near_equal_sizes(n, num_batches):
    bounds = _batch_bounds(n, num_batches)
    assert len(bounds) == num_batches
    assert bounds[0][0] == 0
    assert bounds[-1][1] == n
    sizes = [stop - start for start, stop in bounds]
    assert max(sizes) - min(sizes) <= 1
    # contiguous, no gaps/overlaps, covers [0, n) exactly once
    flat = [i for start, stop in bounds for i in range(start, stop)]
    assert flat == list(range(n))


def test_mini_batch_summary_kmeans_reports_the_same_uneven_batch_bounds(synthetic):
    result = _run(synthetic, max_batch_size=120, max_llm_iter=3, max_iter=30, tol=-1.0)
    assert result.batch_bounds == [(0, 107), (107, 214), (214, 320)]
    assert len(result.summaries) == 3  # one summary_kmeans result per batch


# --- the zero-count fix -------------------------------------------------------------


def test_merge_centroids_matches_upstream_expression_when_denominator_nonzero():
    centroids = np.array([[1.0, 2.0], [3.0, 4.0]])
    counts = np.array([2, 5])
    batch_centroids = np.array([[5.0, 6.0], [7.0, 8.0]])
    batch_counts = np.array([3, 1])

    merged, new_counts = _merge_centroids(centroids, counts, batch_centroids, batch_counts)

    for i in range(2):
        expected = (centroids[i] * counts[i] + batch_centroids[i] * batch_counts[i]) / (
            counts[i] + batch_counts[i]
        )
        assert np.array_equal(merged[i], expected)
    assert np.array_equal(new_counts, counts + batch_counts)


def test_merge_centroids_keeps_previous_centroid_instead_of_upstreams_zero_division():
    centroids = np.array([[1.0, 2.0], [9.0, 9.0]])
    counts = np.array([2, 0])
    batch_centroids = np.array([[5.0, 6.0], [0.0, 0.0]])
    batch_counts = np.array([3, 0])  # cluster 1: 0 + 0 -- upstream computes 0/0 = nan here

    merged, new_counts = _merge_centroids(centroids, counts, batch_centroids, batch_counts)

    assert np.array_equal(merged[1], centroids[1])  # carried forward unchanged
    assert not np.isnan(merged).any()
    assert new_counts[1] == 0


def test_mini_batch_summary_kmeans_survives_a_cluster_with_no_members_in_any_batch(synthetic):
    """n_clusters far exceeds the 6 real blobs, so at least one cluster id never gets a
    member in ANY batch; upstream's centroid merge would divide 0/0 = nan there."""
    texts, X, embed = synthetic
    embedder = LookupEmbedder(embed)
    summarizer = ClosestToMeanSummarizer(embed)
    schedule = FixedSchedule(2, 20)

    result = mini_batch_summary_kmeans(
        texts,
        20,
        summarizer,
        embedder,
        schedule,
        text_features=X,
        max_batch_size=120,
        tol=-1.0,
        random_state=0,
        verbose=False,
    )

    assert not np.isnan(result.centroids).any()


