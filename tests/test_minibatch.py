def test_mini_batch_summary_kmeans_builds_sentences_once_from_the_whole_corpus_when_missing(
    monkeypatch, synthetic
):
    """Extractive-style summarizers need a SentenceCorpus; if the caller doesn't supply
    one, it must be built once from the WHOLE corpus (then sliced per batch) -- unlike
    upstream, which crashed calling `.items()` on a `None` `text_sentences`."""
    texts, X, embed = synthetic
    seen_docs: list[list[str]] = []

    class NeedsSentences(Summarizer):
        needs_sentences = True

        def summarize(self, cluster: Cluster) -> str:
            assert cluster.sentences is not None
            assert cluster.sentence_embeddings is not None
            return closest_to_mean(list(cluster.texts), embed)

    def fake_build(docs, embedder):
        seen_docs.append(list(docs))
        n = len(docs)
        return SentenceCorpus(
            sentences=[f"{d} sentence" for d in docs],
            embeddings=np.zeros((n, X.shape[1]), dtype=np.float32),
            doc_ptr=np.arange(n + 1, dtype=np.int64),
        )

    monkeypatch.setattr(SentenceCorpus, "build", staticmethod(fake_build))

    result = mini_batch_summary_kmeans(
        texts,
        N_BLOBS,
        NeedsSentences(),
        LookupEmbedder(embed),
        FixedSchedule(2, 20),
        text_features=X,
        max_batch_size=120,
        tol=-1.0,
        random_state=0,
        verbose=False,
    )

    assert seen_docs == [texts]  # built exactly once, from every document
    assert result.centroids.shape == (N_BLOBS, X.shape[1])


def test_sequential_mini_batch_kmeans_partial_fits_over_the_upstream_batches(synthetic):
    _, X, _ = synthetic
    model = sequentialMiniBatchKmeans(X, N_BLOBS, random_state=0, max_batch_size=120)
    assert model.cluster_centers_.shape == (N_BLOBS, X.shape[1])
    assignments = model.predict(X)
    assert assignments.shape == (len(X),)


def test_assign_to_centroids_nearest_matches_pairwise_distances_argmin(synthetic):
    from sklearn.metrics import pairwise_distances_argmin

    _, X, _ = synthetic
    centroids = np.asarray(X[:N_BLOBS])
    assert np.array_equal(
        assign_to_centroids(X, centroids, "nearest"), pairwise_distances_argmin(X, centroids)
    )


