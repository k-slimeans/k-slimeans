# --- equivalence with upstream (real data, bank77, relaxed tolerance) ---------------


@pytest.mark.slow
def test_bank77_minibatch_matches_upstream_fixture():
    """Real-data reproduction check: `miniBatchKNLPmeans` (LSA) on Bank77 vs. upstream.

    sklearn's multithreaded KMeans Lloyd reduction is not bit-reproducible on real
    (float32) data -- see the module docstring -- so centroids are compared with a
    tight tolerance rather than exact equality, and assignments/NMI with an agreement
    threshold rather than `np.array_equal`.
    """
    from sklearn.metrics import normalized_mutual_info_score

    from kslimeans.data import load_dataset
    from kslimeans.embeddings import get_embedder

    fixture = _load_fixture("bank77_minibatch_lsa_seed0.npz")

    dataset = load_dataset("bank77")
    embedder = get_embedder("distilbert")
    X = embedder.encode(dataset.texts)

    result: MiniBatchResult = miniBatchKNLPmeans(
        dataset.texts,
        dataset.n_clusters,
        max_batch_size=1000,
        nlp="lsa",
        max_llm_iter=5,
        max_iter=100,
        random_state=0,
        emb_type="distilbert",
        text_features=X,
        top_k=5,
    )

    np.testing.assert_allclose(result.centroids, fixture["centroids"], atol=1e-6, rtol=0)

    assignments = assign_to_centroids(X, result.centroids, "lloyd1")
    agreement = float(np.mean(assignments == fixture["lloyd1_assignments"]))
    assert agreement > 0.999, f"only {agreement:.4%} of bank77 assignments matched the fixture"

    nmi = normalized_mutual_info_score(dataset.labels, assignments)
    assert round(nmi, 4) == round(float(fixture["nmi"]), 4)
