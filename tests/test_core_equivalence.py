"""summary_kmeans must be bit-identical to upstream kSummariesmeans under FixedSchedule.

Re-creates the synthetic corpus and fakes from `tests/fixtures/synth.py` as
`Embedder`/`Summarizer` subclasses, runs `summary_kmeans`, and compares
against the `.npz` fixtures generated by `tests/fixtures/make_fixtures.py`
from the ORIGINAL summaryCentroids.py. Every comparison is exact
(`np.array_equal`), not approximate -- that is the whole point of these
tests.
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pytest

from kslimeans.core import summary_kmeans
from kslimeans.embeddings import Embedder
from kslimeans.schedules import FixedSchedule
from kslimeans.summarizers.base import Cluster, Summarizer

FIXTURES = Path(__file__).resolve().parent / "fixtures"
sys.path.insert(0, str(FIXTURES))
from synth import N_BLOBS, closest_to_mean, make_lookup_embedder, make_synthetic_data  # noqa: E402


class LookupEmbedder(Embedder):
    """Looks each text up in a fixed table -- see synth.make_lookup_embedder."""

    name = "fake"

    def __init__(self, embed):
        self._embed = embed

    def encode(self, texts):
        return self._embed(list(texts))


class ClosestToMeanSummarizer(Summarizer):
    """Returns the member text closest to the members' mean -- see synth.closest_to_mean."""

    needs_sentences = False

    def __init__(self, embed):
        self._embed = embed

    def summarize(self, cluster: Cluster) -> str:
        return closest_to_mean(list(cluster.texts), self._embed)


@pytest.fixture(scope="module")
def synthetic():
    texts, X = make_synthetic_data()
    embed = make_lookup_embedder(texts, X)
    return texts, X, embed


def _run(synthetic, *, initial_iter, final_iter, max_llm_iter, max_iter, tol, force_context_length=0):
    texts, X, embed = synthetic
    embedder = LookupEmbedder(embed)
    summarizer = ClosestToMeanSummarizer(embed)
    schedule = FixedSchedule(max_llm_iter, max_iter, initial_iter, final_iter)
    return summary_kmeans(
        texts,
        N_BLOBS,
        summarizer,
        embedder,
        schedule,
        text_features=X,
        force_context_length=force_context_length,
        tol=tol,
        random_state=0,
        init="k-means++",
        verbose=False,
    )


def _load_fixture(name: str):
    return np.load(FIXTURES / name, allow_pickle=True)


def _assert_matches(result, fixture):
    assert np.array_equal(result.assignments, fixture["assignments"])
    assert np.array_equal(result.centroids, fixture["centroids"])
    assert np.array_equal(result.summary_embeddings, fixture["summary_embeddings"])
    assert list(result.summaries) == list(fixture["summaries"])
    assert len(result.summaries_evolution) == int(fixture["n_summaries_evolution"])
    assert len(result.centroids_evolution) == int(fixture["n_centroids_evolution"])


@pytest.mark.parametrize(
    "initial_iter,final_iter", [(True, True), (True, False), (False, True), (False, False)]
)
def test_matches_fixture_for_each_flag_combo(synthetic, initial_iter, final_iter):
    fixture = _load_fixture(f"synthetic_i{int(initial_iter)}_f{int(final_iter)}.npz")
    result = _run(
        synthetic, initial_iter=initial_iter, final_iter=final_iter, max_llm_iter=3, max_iter=30, tol=-1.0
    )
    _assert_matches(result, fixture)
    assert result.converged is False


def test_tol_break_converges_early_and_matches_fixture(synthetic):
    fixture = _load_fixture("synthetic_tol_break.npz")
    assert bool(fixture["converged"])

    result = _run(synthetic, initial_iter=True, final_iter=True, max_llm_iter=10, max_iter=100, tol=1e-4)

    assert result.converged is True
    _assert_matches(result, fixture)


def test_force_context_length_matches_fixture(synthetic):
    fixture = _load_fixture("synthetic_force_context.npz")
    result = _run(
        synthetic,
        initial_iter=True,
        final_iter=True,
        max_llm_iter=3,
        max_iter=30,
        tol=-1.0,
        force_context_length=5,
    )
    _assert_matches(result, fixture)


def test_summary_kmeans_rejects_non_list_texts(synthetic):
    _, X, embed = synthetic
    with pytest.raises(TypeError):
        summary_kmeans(
            ("not", "a", "list"),
            N_BLOBS,
            ClosestToMeanSummarizer(embed),
            LookupEmbedder(embed),
            FixedSchedule(3, 30),
            text_features=X,
        )
